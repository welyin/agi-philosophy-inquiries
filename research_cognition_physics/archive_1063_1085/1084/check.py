    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='read-only exact comparison with saved JSON')
    args=parser.parse_args();result=run()
    if args.check:
        path=HERE/'results.json'
        if result!=json.loads(path.read_text(encoding='utf-8')):
            raise AssertionError('saved results differ from recomputation')
        print(json.dumps({'round':1084,'status':'exact_saved_results_match',
             'validation_group_count':result['validation_group_count'],
             'assertion_count':result['assertion_count'],
             'checker_sha256':result['checker_sha256'],'results_sha256':sha(path)},indent=2))
    else:print(json.dumps(result,ensure_ascii=False,indent=2))

