CY = np.kron((I2+Y)/2, I2) + np.kron((I2-Y)/2, X)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def norm(a):
    return float(np.linalg.norm(a, 2))


def close_zero(a, label, tol=2e-11):
    value = norm(a)
    assert value < tol, (label, value)
    return value


def unitary(h, t):
    e, v = np.linalg.eigh(h)
    return (v*np.exp(-1j*t*e)) @ v.conj().T


def source_group():
    q = .37
    B = (I2+X)/2
    u, v = unitary(A,q), unitary(B,q)
    du, dv = -1j*A@u, -1j*B@v
    direct = 1j*(u@v).conj().T@(du@v+u@dv)
    composed = v.conj().T@A@v+B
    errors = {
        'source_composition': close_zero(direct-composed, 'composition'),
        'hermiticity': close_zero(direct-direct.conj().T, 'Hermitian source'),
        'periodic_u': close_zero(unitary(A,q+2*math.pi)-u, 'circle U'),
        'periodic_v': close_zero(unitary(B,q+2*math.pi)-v, 'circle V'),
    }
    # Independent extremal-state lower witness and scalar-centering upper bound.
    witnesses=[]
    for j in [composed, np.diag([-2., .25, 3.]).astype(complex)]:
        es, vs = np.linalg.eigh(j)
        psi = (vs[:,0]+vs[:,-1])/math.sqrt(2)
        rho = np.outer(psi,psi.conj())
        tangent = -1j*(j@rho-rho@j)
        lower = float(np.sum(np.abs(np.linalg.eigvalsh(tangent))))
        upper = 2*norm(j-(es[0]+es[-1])/2*np.eye(len(j)))
        diameter = float(es[-1]-es[0])
        assert abs(lower-diameter)<2e-12 and abs(upper-diameter)<2e-12
        witnesses.append({'dimension':len(j),'diameter':diameter,
                          'extremal_state_trace_norm':lower,'centering_upper':upper})
    c0=[]
    for n in [16,64,256]:
        # U_N(q)=exp[-i sin(Nq) A/sqrt(N)], exactly 2pi-periodic.
        channel_sup = 2*math.sin(1/(2*math.sqrt(n)))
        source_diameter_at_zero=math.sqrt(n)
        assert channel_sup<=1/math.sqrt(n)
        c0.append({'N':n,'channel_C0_sup':channel_sup,
                   'source_diameter_at_zero':source_diameter_at_zero})
    return {'status':'PASS','errors':errors,'diamond_tangent_witnesses':witnesses,
            'C0_does_not_bound_derivative':c0,
            'proof_not_SDP_or_samples':'Extremal-state lower witness plus complete-norm upper proof.'}


def apply_link(state, link, n):
    """Finite Fourier dictionary, each value is a 4 x input-column matrix.

    Integer keys are generated by exact shifts. There is no fixed momentum grid.
    """
    out={}
    for k,b in state.items():
        if link in ('W','Wdag'):
            sign=1 if link=='W' else -1
            for a in [0,1]:
                dest=k+sign*(n-a)
                val=np.zeros_like(b); val[2*a:2*a+2]=b[2*a:2*a+2]
                out[dest]=out.get(dest,np.zeros_like(b))+val
        elif link=='F':
            out[k]=np.exp(-.5j*math.pi*k*k)*b
        elif link=='Fdag':
            out[k]=np.exp(.5j*math.pi*k*k)*b
        elif link=='CY':
            out[k]=CY@b
        else:
            raise ValueError(link)
    return {k:b for k,b in out.items() if norm(b)>1e-14}


def dictionary_error(left,right):
    keys=sorted(set(left)|set(right)); blank=np.zeros((4,4),complex)
    return norm(np.vstack([left.get(k,blank)-right.get(k,blank) for k in keys]))


def prefixes(n):
    states=[{0:np.eye(4,dtype=complex)}]
    for link in ['W','F','Wdag','CY']:
        states.append(apply_link(states[-1],link,n))
    return states


def phase_group():
    q=.71
    u0=unitary(A,q); u1=np.exp(1j*q)*u0
    ch0=np.kron(u0,u0.conj()); ch1=np.kron(u1,u1.conj())
    channel_error=close_zero(ch0-ch1,'same fixed-q channel')
    rows=[]
    for n in [0,1]:
        states=prefixes(n)
        dn=np.diag(np.exp(-.5j*math.pi*(np.arange(2)-n)**2))
        target={0:np.kron(dn,I2)}
        loop_error=dictionary_error(states[3],target)
        assert loop_error<2e-12
        inverse_errors=[]
        for j, inverse in enumerate(['Wdag','Fdag','W','CY'],start=1):
            inverse_errors.append(dictionary_error(apply_link(states[j],inverse,n),states[j-1]))
        assert max(inverse_errors)<2e-12
        psi=dn@PLUS
        y=float(np.vdot(psi,Y@psi).real)
        assert abs(y-(-1 if n==0 else 1))<2e-12
        rows.append({'n':n,'J_eigenvalues':(np.arange(2)-n).tolist(),
                     'prefix_momentum_support':[sorted(x) for x in states],
                     'loop_error':loop_error,'inverse_link_errors':inverse_errors,
                     'ideal_Y_expectation':y,'rotor_returns_p0':set(states[3])=={0}})
    return {'status':'PASS','fixed_q_D_channel_difference':channel_error,
            'cases':rows,'ideal_record_gap':1.,
            'same_channel_scope':'Known n restrictions on D; not the full coherent N x D channel.'}


def closed_group():
    jx=np.zeros((5,5),complex)
    for j in range(4):
        jx[j,j+1]=jx[j+1,j]=.5*math.sqrt((j+1)*(4-j))
    base=2*np.eye(5)-jx
    h0=np.kron(base,np.eye(4))
    ein=np.zeros((20,2),complex)
    for a in range(2): ein[2*a,a]=1
    ideal=np.zeros_like(ein); ideal[16:20]=ein[:4]
    pst_error=close_zero(unitary(h0,TIME)@ein-ideal,'spin2 transfer')
    eps=TIME/(2*INERTIA)
    cases=[]; record_probabilities=[]
    for n in [0,1]:
        states=prefixes(n)
        modes=sorted(set().union(*(set(s) for s in states)))
        # An explicit embedding of the exact sector, not a cutoff Hamiltonian.
        bmap=np.zeros((5*len(modes)*4,20),complex)
        p2physical=np.zeros(5*len(modes)*4)
        recordphysical=np.zeros_like(p2physical)
        for j,state in enumerate(states):
            for k in modes:
                start=(j*len(modes)+modes.index(k))*4
                if k in state: bmap[start:start+4,4*j:4*j+4]=state[k]
                p2physical[start:start+4]=k*k
                recordphysical[start:start+4]=[0,1,0,1]
        close_zero(bmap.conj().T@bmap-np.eye(20),'exact sector isometry')
        p2=np.zeros((20,20),complex)
        for j in [1,2]:
            p2[4*j:4*j+4,4*j:4*j+4]=np.kron(np.diag((np.arange(2)-n)**2),I2)
        invariance=close_zero(p2physical[:,None]*bmap-bmap@p2,'p2 reducing sector')
        h=h0+p2/(2*INERTIA)
        u=unitary(h,TIME); actual=u@ein
        iso_error=norm(actual-ideal)
        assert iso_error<=eps+1e-12
        effect=bmap.conj().T@(recordphysical[:,None]*bmap)
        prob=float(np.vdot(actual@PLUS,effect@(actual@PLUS)).real)
        record_probabilities.append(prob)
        head4=np.diag([0.]*16+[1.]*4)
        failure=1-float(np.vdot(actual@PLUS,head4@(actual@PLUS)).real)
        energy_in=ein.conj().T@h@ein
        energy_final=actual.conj().T@h@actual
        energy_error=close_zero(energy_final-energy_in,'complete H conservation')
        close_zero(energy_in-2*np.eye(2),'input energy including program')
        kinetic=actual.conj().T@(p2/(2*INERTIA))@actual
        program=actual.conj().T@h0@actual
        close_zero(kinetic+program-energy_in,'resource partition')
        # Independent 5 x 5 scalar branch: only one logical branch sees the cost.
        hbad=base+np.diag([0,1,1,0,0])/(2*INERTIA)
        z=unitary(hbad,TIME)[4,0]
