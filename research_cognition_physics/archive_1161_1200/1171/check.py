        assert abs(prob-scalar_prob)<3e-12
        evals=np.linalg.eigvalsh(h)
        assert evals[0]>-2e-12 and evals[-1]<=4+1/(2*INERTIA)+2e-12
        # Explicit maximally entangled reference diagnostic; the theorem is uniform.
