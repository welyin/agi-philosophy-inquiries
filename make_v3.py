def set_text(p, text):
    """保留第一个 run 的格式，替换文本"""
    runs = p.runs
    assert runs, 'no runs'
    runs[0].text = text
    for r in runs[1:]:
        r._element.getparent().remove(r._element)

def clone_para(template_p, text):
    """从模板段落深拷贝一个段落元素并替换文本"""
    el = deepcopy(template_p._p)
    runs = el.findall(W + 'r')
    for r in runs[1:]:
        el.remove(r)
    r0 = runs[0]
    for child in list(r0):
        if child.tag not in (W + 'rPr', W + 't'):
            r0.remove(child)
    t = r0.find(W + 't')
    t.text = text
    t.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
    return el

